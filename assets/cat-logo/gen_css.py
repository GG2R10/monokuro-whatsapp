#!/usr/bin/env python3
"""Turns assets/cat-logo/whatsapp-cat-logo.svg (made by gen.py) into src/fx/30-logo-cat.css.
The artwork has four colours; they become two ALPHA MASKS so the page colours drive them:
  ink layer    = the white shapes (alpha 1) + the floor shadow (#3a3a3a, which is 22.75% white on black -> alpha .2275)   painted with --mk-ink
  accent layer = the pink details (nose, ear, blush)                                                                   painted with --mk-logo-accent
The black fill of the face is dropped: the header behind it is the paper colour anyway.
Both masks keep the SVG's own CSS animations (bobbing, blinking, ear twitch, letters hopping)."""
import re
from urllib.parse import quote
svg = open('assets/cat-logo/whatsapp-cat-logo.svg').read()

def layer(keep, alpha=None):
    out = svg
    cols = ('#fff', '#ff6ec7', '#3a3a3a', '#000')
    for k, col in enumerate(cols):                       # first -> neutral placeholders, so a replacement can never be re-matched by the next one
        out = out.replace(f"fill='{col}'", f"fill='@@{k}@@'")
    for k, col in enumerate(cols):
        if col in keep: out = out.replace(f"fill='@@{k}@@'", "fill='#000'" + (f" fill-opacity='{alpha[col]}'" if alpha and col in alpha else ''))
        else:           out = out.replace(f"fill='@@{k}@@'", "fill='none'")
    return out

def uri(s): return 'url("data:image/svg+xml,' + quote(s, safe=" '=:/;,()!*.-_{}") + '")'

ink = layer({'#fff', '#3a3a3a'}, {'#3a3a3a': 0.2275})
accent = layer({'#ff6ec7'})
css = f'''/* FX: animated pixel-art cat + "WhatsApp" wordmark replacing WhatsApp's wordmark (chat-list header).  GENERATED by assets/cat-logo/gen_css.py - edit the art in gen.py.
   The art is two alpha masks of the same animated SVG (~12 KB each as a data: URI, allowed by WhatsApp's CSP), so the logo follows the theme colours:
     ink layer    -> --mk-ink            (outline, eyes, whiskers, letters, floor shadow at 22.75% alpha)
     accent layer -> --mk-logo-accent    (nose, ear, blush)
   The face fill is not drawn: the header behind the logo is the paper colour.
   The art is 64x18 px, so it is rendered at an integer multiple (128x36 = 2x) to keep the pixels crisp. */
:root {{ --mk-cat-ink: {uri(ink)}; --mk-cat-accent: {uri(accent)}; --mk-logo-accent: #ff6ec7; }}
#app [data-testid="wa-wordmark"]:not(#_) {{ position: relative !important; width: 128px !important; height: 36px !important; display: inline-block !important; }}
#app [data-testid="wa-wordmark"]:not(#_)::before, #app [data-testid="wa-wordmark"]:not(#_)::after {{ content: ""; position: absolute; inset: 0; image-rendering: pixelated; }}
#app [data-testid="wa-wordmark"]:not(#_)::before {{ background-color: var(--mk-ink); -webkit-mask: var(--mk-cat-ink) 0 0 / 100% 100% no-repeat; mask: var(--mk-cat-ink) 0 0 / 100% 100% no-repeat; }}
#app [data-testid="wa-wordmark"]:not(#_)::after {{ background-color: var(--mk-logo-accent); -webkit-mask: var(--mk-cat-accent) 0 0 / 100% 100% no-repeat; mask: var(--mk-cat-accent) 0 0 / 100% 100% no-repeat; }}
#app [data-testid="wa-wordmark"] > svg:not(#_) {{ display: none !important; }}
'''
open('src/fx/30-logo-cat.css', 'w').write(css)
print('src/fx/30-logo-cat.css', len(css), 'bytes;', 'ink mask', len(uri(ink)), 'accent mask', len(uri(accent)))
